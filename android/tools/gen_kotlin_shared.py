"""Generate files the Kotlin phone shares with the Python code, so they can never drift.

    python android/tools/gen_kotlin_shared.py

Writes:
  core/src/main/kotlin/org/meshlearn/core/Zdict.kt   the preset compression dictionary (protocol.ZDICT)
  core/src/test/resources/vectors.json              frames and values made by the Python code,
                                                     which the Kotlin tests must read identically
Run it again whenever protocol.py or assignments.py changes.
"""

import base64
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, REPO)

from meshlearn import assignments as asg  # noqa: E402
from meshlearn import protocol  # noqa: E402

CORE = os.path.join(HERE, "..", "core", "src")

zdict_b64 = base64.b64encode(protocol.ZDICT).decode("ascii")
chunks = [zdict_b64[i:i + 100] for i in range(0, len(zdict_b64), 100)]
kotlin = (
    "// Generated by android/tools/gen_kotlin_shared.py from meshlearn/protocol.py. Do not edit.\n"
    "package org.meshlearn.core\n\n"
    "import java.util.Base64\n\n"
    "internal object Zdict {\n"
    f"    const val VERSION = {protocol.VERSION}\n"
    "    val BYTES: ByteArray = Base64.getDecoder().decode(\n"
    + " +\n".join(f'        "{c}"' for c in chunks)
    + "\n    )\n}\n"
)
with open(os.path.join(CORE, "main", "kotlin", "org", "meshlearn", "core", "Zdict.kt"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write(kotlin)

# -- test vectors -------------------------------------------------------------
samples = [
    ("h", {"n": "North village", "f": 1234, "l": 3, "sw": "0.1.0", "inv": {"a1b2c3": "deadbeef"}}),
    ("o", {"a": "a1b2c3", "v": "0badf00d", "o": 1, "d": "2026-11-20"}),
    ("k", {"id": 305419896}),
    ("x", {"id": 305419896, "m": [0, 2]}),
    ("r", {"r": [{"id": "s01", "sc": 2.5, "mx": 4.0, "ok": 1, "q": {"q1": 1.0, "q2": None}}]}),
    ("s", {"s": [{"id": "s1a2b3c4", "a": "a1b2c3", "v": "0badf00d", "u": "Lena Müller", "x": {"q1": "2", "q2": "3,5"}, "t": 1763200000, "d": 95}]}),
]
with open(os.path.join(REPO, "meshlearn", "sample_assignment.json"), encoding="utf-8") as fh:
    sample = asg.normalize_assignment(json.load(fh))
sample["id"] = "a1b2c3"
big_payload = {"a": asg.pack(dict(asg.public_view(sample), version=asg.version_of(sample))), "o": 1, "d": ""}
samples.append(("a", big_payload))

messages = []
for i, (mtype, payload) in enumerate(samples):
    msg_id, frames = protocol.encode(mtype, payload, msg_id=0x10000000 + i)
    messages.append({"type": mtype, "payload": payload, "msg_id": msg_id,
                     "frames": [base64.b64encode(f).decode("ascii") for f in frames]})

assignments = []
for a in (sample, asg.public_view(sample), dict(sample, mode="practice")):
    assignments.append({"assignment": a, "packed": asg.pack(a), "version": asg.version_of(a)})

numbers = {t: asg.parse_number(t) for t in ["3.5", "3,5", "1/2", " 12 ", "-4", "1e3", ".5", "abc", "1/0", "2/", "", "+7,25"]}
floats = {repr(x): x for x in [1.0, 0.5, 0.1, 2.25, 1e-05, 123456789.0, 1e16, 1.5e16, -0.75, 3.0e-4]}

vectors = {"messages": messages, "assignments": assignments, "parse_number": numbers,
           "float_repr": {k: v for k, v in floats.items()}, "zdict_len": len(protocol.ZDICT)}

# Meshtastic protobufs, from the official definitions, when the meshtastic package is installed.
try:
    from meshtastic.protobuf import mesh_pb2, portnums_pb2

    frame = protocol.encode("k", {"id": 1}, msg_id=7)[1][0]
    to = mesh_pb2.ToRadio()
    to.packet.to = 0xA1B2C3D4
    to.packet.channel = 3
    to.packet.decoded.portnum = portnums_pb2.PortNum.PRIVATE_APP
    to.packet.decoded.payload = frame
    to.packet.id = 0x01020304
    to.packet.hop_limit = 2
    to.packet.want_ack = True
    fr = mesh_pb2.FromRadio()
    getattr(fr.packet, "from").__class__  # noqa: B018 (field named "from")
    setattr(fr.packet, "from", 0x11223344)
    fr.packet.to = 0xA1B2C3D4
    fr.packet.channel = 3
    fr.packet.decoded.portnum = portnums_pb2.PortNum.PRIVATE_APP
    fr.packet.decoded.payload = frame
    fr.packet.rx_snr = 6.25
    info = mesh_pb2.FromRadio()
    info.my_info.my_node_num = 0xA1B2C3D4
    want = mesh_pb2.ToRadio(want_config_id=42)
    b64 = lambda m: base64.b64encode(m.SerializeToString()).decode("ascii")  # noqa: E731
    vectors["meshtastic"] = {"payload": base64.b64encode(frame).decode("ascii"), "to_radio": b64(to),
                             "from_radio": b64(fr), "my_info": b64(info), "want_config": b64(want)}
    print("included Meshtastic protobuf vectors")
except ImportError:
    print("meshtastic not installed: skipping its protobuf vectors")

with open(os.path.join(CORE, "test", "resources", "vectors.json"), "w", encoding="utf-8", newline="\n") as fh:
    json.dump(vectors, fh, ensure_ascii=False, indent=1)
print(f"wrote Zdict.kt ({len(protocol.ZDICT)} bytes) and vectors.json ({len(messages)} messages)")
